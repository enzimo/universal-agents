"""The tracked Web Chat transcript schemas must match the transcript models.

The schemas under data/schemas/gateway/transcript/v1 are generated by
scripts/export_gateway_transcript_contract.py. They once went stale for weeks
because nothing compared them with the models; these tests fail as soon as a
model change is not regenerated, and check that the conformance fixtures mean
the same thing to the JSON Schema and to the Python models.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from jsonschema import Draft202012Validator, FormatChecker
from pydantic import ValidationError

from assistant_gateway.application import website_application
from scripts.export_gateway_transcript_contract import (
    FIXTURE_PATH,
    OUTPUT_DIR,
    stale_transcript_contract_files,
)


def _validator(model_name: str) -> Draft202012Validator:
    schema = json.loads((OUTPUT_DIR / f"{model_name}.schema.json").read_text(encoding="utf-8"))
    Draft202012Validator.check_schema(schema)
    return Draft202012Validator(schema, format_checker=FormatChecker())


def _cases(section: str) -> list[dict]:
    return json.loads(Path(FIXTURE_PATH).read_text(encoding="utf-8"))[section]


def test_tracked_transcript_schemas_match_the_models() -> None:
    assert stale_transcript_contract_files() == [], (
        "Regenerate with: .venv/bin/python scripts/export_gateway_transcript_contract.py"
    )


@pytest.mark.parametrize("case", _cases("valid"), ids=lambda case: case["name"])
def test_valid_fixtures_pass_the_schema_and_the_model(case: dict) -> None:
    _validator(case["model"]).validate(case["payload"])
    getattr(website_application, case["model"]).model_validate(case["payload"])


@pytest.mark.parametrize("case", _cases("invalid"), ids=lambda case: case["name"])
def test_invalid_fixtures_fail_the_schema_and_the_model(case: dict) -> None:
    assert list(_validator(case["model"]).iter_errors(case["payload"])), case["name"]
    with pytest.raises(ValidationError):
        getattr(website_application, case["model"]).model_validate(case["payload"])


def test_fixtures_cover_the_browser_request_id() -> None:
    assert any(
        "client_request_id" in case["payload"] for case in _cases("valid")
    ), "keep a valid fixture for the optional client_request_id field"
